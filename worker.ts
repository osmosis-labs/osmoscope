// Cloudflare Worker entry: the OpenNext build of the Next.js app, with an edge
// cache in front of the API routes, and a cron trigger that checks the
// rate-limit monitor is still running (lib/heartbeat.ts). The data crons
// themselves run from GitHub Actions, see .github/workflows/cron.yml.
//
// Vercel's CDN cached the API routes from their `Cache-Control: s-maxage`, so
// database reads grew with routes and cache windows, not visitors. Cloudflare
// does not cache a Worker's own responses from that header, so this does it
// with the Cache API: a hit is served without running the app or touching the
// database.
//
// The import exists only after `opennextjs-cloudflare build`, so it needs an
// ignore directive that holds both before and after the build.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore: generated by the OpenNext build
import { default as handler } from "./.open-next/worker.js";
import { canonicalApiUrl, withSecurityHeaders } from "./lib/edge";
import { runHeartbeat, type HeartbeatEnv } from "./lib/heartbeat";

type Ctx = { waitUntil(p: Promise<unknown>): void };

// The edge copy carries a max-age (the Cache API's expiry) in place of the
// route's own header, which rides along here and is restored on a hit, so a
// visitor gets the same Cache-Control from a hit as from a miss.
const ORIGIN_CACHE_CONTROL = "x-origin-cache-control";

const sMaxAge = (cacheControl: string | null): number | null => {
  const match = cacheControl?.match(/(?:^|,)\s*s-maxage=(\d+)/i);
  return match ? Number(match[1]) : null;
};

const isCachedApi = (request: Request): boolean => {
  if (request.method !== "GET") return false;
  const { pathname } = new URL(request.url);
  return pathname.startsWith("/api/") && !pathname.startsWith("/api/cron/");
};

const worker = {
  // Cron trigger (wrangler.jsonc): checks that the rate-limit monitor, which
  // runs on GitHub Actions, is still running (lib/heartbeat.ts). It asks the
  // app directly, past the edge cache, for the stored snapshot, and judges it
  // at the trigger's exact slot time.
  async scheduled(
    controller: { scheduledTime: number },
    env: unknown,
    ctx: Ctx
  ): Promise<void> {
    const result = await runHeartbeat({
      fetchSnapshot: () =>
        handler.fetch(
          new Request("https://osmoscope.osmosis.zone/api/rate-limits"),
          env,
          ctx
        ),
      env: (env ?? {}) as HeartbeatEnv,
      slotMs: controller.scheduledTime,
    });
    console.log(`Heartbeat: ${result}`);
  },

  // Every response, page or API, hit or miss, carries the security headers.
  async fetch(request: Request, env: unknown, ctx: Ctx): Promise<Response> {
    return withSecurityHeaders(await serve(request, env, ctx));
  },
};

async function serve(
  request: Request,
  env: unknown,
  ctx: Ctx
): Promise<Response> {
  if (!isCachedApi(request)) return handler.fetch(request, env, ctx);

  // Cache under the canonical URL, so an unread or reordered query parameter
  // cannot force a miss (each miss runs the app and reads the database).
  const canonical = canonicalApiUrl(new URL(request.url));
  const cacheKey = canonical ? new Request(canonical.toString()) : request;

  const cache = (caches as unknown as { default: Cache }).default;
  const hit = await cache.match(cacheKey);
  if (hit) {
    const response = new Response(hit.body, hit);
    const original = response.headers.get(ORIGIN_CACHE_CONTROL);
    if (original) response.headers.set("cache-control", original);
    response.headers.delete(ORIGIN_CACHE_CONTROL);
    return response;
  }

  const response: Response = await handler.fetch(request, env, ctx);
  const cacheControl = response.headers.get("cache-control");
  const seconds = sMaxAge(cacheControl);
  if (response.status === 200 && cacheControl && seconds) {
    // The edge copy expires after s-maxage.
    const copy = new Response(response.clone().body, response);
    copy.headers.set(ORIGIN_CACHE_CONTROL, cacheControl);
    copy.headers.set("cache-control", `public, max-age=${seconds}`);
    ctx.waitUntil(cache.put(cacheKey, copy));
  }
  return response;
}

export default worker;
